export type IconName = keyof typeof PATHS;

interface IconProps {
  name: string;
  size?: number;
  title?: string;
  style?: CSSProperties;
}

export function Icon({ name, size = 18, title, style }: IconProps) {
  const body = PATHS[name];
  if (!body) return null;
  return (
    <svg
      role={title ? 'img' : 'presentation'}
      aria-label={title}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      style={{ display: 'inline-block', flex: '0 0 auto', color: 'inherit', lineHeight: 0, ...style }}
    >
      {body}
    </svg>
  );
}
